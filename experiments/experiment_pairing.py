"""The pairing signature spotted in experiment_weight2.py, and whether it
explains the C15 constancy (TODO step 3).

Observation: in the top-12 coefficient listing, every coefficient appeared
TWICE at equal magnitude, once with the exponent qubit e13 set and once
without -- (z, z XOR e) pairs. If the Walsh support is closed under XOR with
each exponent qubit, that is a hard structural constraint, and it is the most
promising route to PROVING the circuit-level invariance that Paper B currently
reports as empirical.

Tests:
  P1  Is the support closed under z -> z XOR e_i for each exponent qubit?
  P2  Do paired coefficients have equal magnitude? Equal sign, or opposite?
  P3  Does the structure differ between r = power of two and r with an odd
      factor?  (If the pairing holds only for r=2^k, it IS the mechanism.)
"""
from __future__ import annotations
import numpy as np
from toffoli_arith import ToffoliModExp
import walsh


def analyse(N, a, ne, label):
    me = ToffoliModExp(N=N, a=a, n_exp=ne)
    qc = me.build()
    c = walsh.pullback_coefficients(qc, me.x[0])
    nz = np.abs(c) > 1e-12
    idx = np.nonzero(nz)[0]
    S = idx.size
    print(f"\n  {label}: r={me.order()}, n_exp={ne}, q={qc.n}, |support|={S}")
    for i, eq in enumerate(me.exp):
        bit = 1 << eq
        partner = idx ^ bit
        closed = bool(nz[partner].all())
        # magnitudes equal?
        eqmag = bool(np.allclose(np.abs(c[idx]), np.abs(c[partner]), atol=1e-12))
        if closed:
            same = int(np.sum(np.sign(c[idx]) == np.sign(c[partner])))
            opp = S - same
            sgn = f"same-sign {same}, opposite {opp}"
        else:
            miss = int((~nz[partner]).sum())
            sgn = f"{miss}/{S} partners missing"
        print(f"    exp qubit {eq} (e{i}): support closed = {str(closed):5s}  "
              f"|c| equal = {str(eqmag):5s}   {sgn}")
    return me, c, nz


print("=" * 78)
print("P1/P2  Is the support closed under XOR with an exponent qubit?")
print("=" * 78)
analyse(5, 2, 1, "modexp N=5 a=2  (r=4, power of two)")
analyse(7, 6, 2, "modexp N=7 a=6  (r=2, power of two)")
analyse(7, 3, 2, "modexp N=7 a=3  (r=6, ODD factor)")

print()
print("=" * 78)
print("P3  Does the pairing distinguish power-of-two r from odd-factor r?")
print("=" * 78)
print("  Sweeping n_exp for both cases at N=7.\n")
print(f"  {'a':>3} {'r':>3} {'n_exp':>6} {'|support|':>10} {'all exp bits paired?':>22}")
for a, r_ in ((6, 2), (3, 6)):
    for ne in (1, 2, 3, 4):
        me = ToffoliModExp(N=7, a=a, n_exp=ne)
        qc = me.build()
        c = walsh.pullback_coefficients(qc, me.x[0])
        nz = np.abs(c) > 1e-12
        idx = np.nonzero(nz)[0]
        allp = all(bool(nz[idx ^ (1 << eq)].all()) for eq in me.exp)
        print(f"  {a:3d} {r_:3d} {ne:6d} {idx.size:10d} {str(allp):>22}", flush=True)
    print()

print("""  If the support is closed under XOR with every exponent qubit, then it is a
  union of cosets of the subgroup generated by those qubits. Its size is then a
  multiple of 2^n_exp -- which would make CONSTANT support impossible unless the
  support shrinks correspondingly in the non-exponent coordinates. Whichever way
  this lands, it constrains the C15 mechanism sharply.""")

"""Exact regrouping for coherent reflection routes on coarse sectors.

DERIVED BEFORE MEASUREMENT.  Write r=b*M and use the U^b sectors
|alpha,p>.  A cell reflection R maps m to -m mod M, while

    J_q = D_q R,       D_q|b*m+p> = exp(+2*pi*i*q*m/M)|b*m+p>

routes alpha to f_q(alpha)=-alpha-q.  A coherent reflection gate is
K_q(theta)=cos(theta/2)I-i*sin(theta/2)J_q.  For one fixed q, every orbit of
f_q has size at most two, so the full-r circuit can be grouped into a
finite coherent work space containing only those sectors.  Multiple q values
generate translations q_i-q_j; their orbit size is determined by a gcd and
can reach all sectors when M is prime and q=0,1 are both present.

P1: exact integer reflection-orbit partitions agree with the gcd formula,
    including huge M evaluated without sector arrays; J_q is Hermitian/unitary.
P2: for fixed q and r=10,14, the coherent grouped sequential_path marginal
    agrees with the full-r original-order marginal at t=5, with normalized
    coherent initial |p=0> over each group and group weight |G|/M.
P3: two reflection choices q=0,1 close under the gcd partition, and the
    grouped finite-work law (history count 4) still agrees with full-r.

C1: dropping the coherent initial superposition inside a size-two group must
    fail for a nonzero reflection angle.
C2: replacing the actual output law by a uniform-output target must fail.

The fixed background has repeated b=2 W rotations after controls 1,3,4;
reflections are inserted after controls 2 (one-q tests) and 2,4 (two-q test).
All route construction, sector grouping, and full-r references are supplied
known-index finite calculations.  This is not a generic propagator or a
hardness claim.  Dense diagnostics are capped at r<=14,t=5; the huge-M gcd
case allocates no M-indexed array.

Run: OPENBLAS_NUM_THREADS=1 uv run --no-project --python 3.12 --with
    'numpy<2.5' python -m experiments.experiment_route_regrouping
"""
from __future__ import annotations

import json
import math
import traceback
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

from lab import Experiment
from lab.semiclassical import sequential_path


MAX_DENSE_BYTES = 16 * 1024 * 1024
MAX_R = 14
WIDTH = 5
B = 2
ANGLE = np.pi / 4


def guard(shape, dtype, label: str) -> int:
    payload = math.prod(int(x) for x in shape) * np.dtype(dtype).itemsize
    if payload > MAX_DENSE_BYTES:
        raise MemoryError(f"{label} allocation {payload} bytes exceeds 16 MiB")
    return payload


def report_path(prefix: str = "route_regrouping") -> Path:
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    root = Path("out")
    root.mkdir(parents=True, exist_ok=True)
    path = root / f"{prefix}_{stamp}.json"
    serial = 0
    while path.exists():
        serial += 1
        path = root / f"{prefix}_{stamp}_{serial}.json"
    return path


def reflection_orbit(M: int, qs: tuple[int, ...], alpha: int) -> tuple[int, ...]:
    if not 1 <= M <= 12 or not qs or not 0 <= alpha < M:
        raise ValueError("invalid reflection orbit input")
    seen = {alpha}
    frontier = [alpha]
    while frontier:
        x = frontier.pop()
        for q in qs:
            y = (-x - q) % M
            if y not in seen:
                seen.add(y)
                frontier.append(y)
    return tuple(sorted(seen))


def gcd_orbit_size(M: int, qs: tuple[int, ...], alpha: int) -> tuple[int, int, int]:
    """Return gcd g and exact orbit size without enumerating M sectors."""
    if M < 1 or not qs or not 0 <= alpha < M:
        raise ValueError("invalid gcd orbit input")
    q0 = qs[0] % M
    g = M
    for q in qs[1:]:
        g = math.gcd(g, (q - q0) % M)
    # Translations generated by q_i-q_0 form multiples of g.  Reflections
    # either preserve alpha mod g or add one second residue class.
    c0 = alpha % g
    c1 = (-alpha - q0) % g
    cosets = 1 if c0 == c1 else 2
    return g, cosets, cosets * (M // g)


def sector_basis(r: int, b: int, alpha: int) -> np.ndarray:
    M = r // b
    if r < 1 or r > MAX_R or b < 1 or r % b or not 0 <= alpha < M:
        raise ValueError("invalid finite sector dimensions")
    guard((r, b), np.complex128, "sector basis")
    result = np.zeros((r, b), dtype=complex)
    for m in range(M):
        result[b*m:b*m+b, :] = np.eye(b) * np.exp(-2j*np.pi*alpha*m/M) / np.sqrt(M)
    return result


def rx_block(theta: float = np.pi / 2) -> np.ndarray:
    c, s = np.cos(theta / 2), -1j * np.sin(theta / 2)
    return np.array([[c, s], [s, c]], dtype=complex)


def repeated_block(r: int, block: np.ndarray) -> np.ndarray:
    if r % B:
        raise ValueError("r must be divisible by b")
    guard((r, r), np.complex128, "repeated background")
    result = np.zeros((r, r), dtype=complex)
    for start in range(0, r, B):
        result[start:start+B, start:start+B] = block
    return result


def shift_matrix(r: int, power: int) -> np.ndarray:
    guard((r, r), np.complex128, "orbit shift")
    result = np.zeros((r, r), dtype=complex)
    for j in range(r):
        result[(j + power) % r, j] = 1.
    return result


def reflection(r: int, q: int) -> np.ndarray:
    if r % B:
        raise ValueError("reflection requires b|r")
    M = r // B
    guard((r, r), np.complex128, "reflection")
    result = np.zeros((r, r), dtype=complex)
    for m in range(M):
        for p in range(B):
            source = B*m + p
            target = B*((-m) % M) + p
            result[target, source] = 1.
    return result


def character(r: int, q: int) -> np.ndarray:
    M = r // B
    guard((r, r), np.complex128, "character diagonal matrix")
    values = np.array([np.exp(2j*np.pi*q*(j//B)/M) for j in range(r)], complex)
    return np.diag(values)


def reflection_gate(r: int, q: int, theta: float) -> np.ndarray:
    J = character(r, q) @ reflection(r, q)
    return np.cos(theta / 2) * np.eye(r) - 1j*np.sin(theta / 2) * J


def background_pairs(r: int, reflection_qs: dict[int, int], theta: float = ANGLE,
                    reflection_angle: float = ANGLE) -> list[tuple[np.ndarray, np.ndarray]]:
    """Full-r original ascending order with W after 1,3,4."""
    if r > MAX_R or any(s not in (2, 4) for s in reflection_qs):
        raise ValueError("reflection insertion outside fixed audit schedule")
    identity = np.eye(r, dtype=complex)
    W = repeated_block(r, rx_block(np.pi / 2))
    posts = {1: W, 3: W, 4: W}
    for s, q in reflection_qs.items():
        posts[s] = reflection_gate(r, q, reflection_angle) @ posts.get(s, identity)
    pairs = []
    for i in range(WIDTH):
        post = posts.get(i + 1, identity)
        pairs.append((post, post @ shift_matrix(r, 1 << i)))
    return pairs


def full_marginal(r: int, reflection_qs: dict[int, int], *, angle: float = ANGLE) -> np.ndarray:
    pairs = background_pairs(r, reflection_qs, reflection_angle=angle)
    initial = np.eye(r, dtype=complex)[:, 0]
    guard((1 << WIDTH,), np.float64, "full marginal")
    return np.array([sequential_path(pairs, initial, output=y)[
        "conditional_path_probability"] for y in range(1 << WIDTH)])


def grouped_marginal(r: int, reflection_qs: dict[int, int], *, angle: float = ANGLE,
                    coherent_initial: bool = True) -> tuple[np.ndarray, list[dict]]:
    if not 1 <= r <= MAX_R or r % B:
        raise ValueError("grouped reference exceeds finite orbit cap")
    M = r // B
    qs = tuple(reflection_qs.values())
    groups = []
    unseen = set(range(M))
    while unseen:
        alpha = min(unseen)
        group = reflection_orbit(M, qs, alpha)
        groups.append(group)
        unseen.difference_update(group)
    result = np.zeros(1 << WIDTH, dtype=float)
    details = []
    for group in groups:
        g = len(group)
        # Q_group is r x (g*b); use explicit projection only at bounded M.
        dim = g * B
        guard((r, dim), np.complex128, "group projection")
        basis = np.column_stack([sector_basis(r, B, alpha) for alpha in group])
        pairs = background_pairs(r, reflection_qs, reflection_angle=angle)
        local_pairs = [(basis.conj().T @ B0 @ basis,
                        basis.conj().T @ B1 @ basis) for B0, B1 in pairs]
        if coherent_initial:
            initial = np.zeros(dim, dtype=complex)
            for gi in range(g):
                initial[gi*B] = 1 / np.sqrt(g)
            local = np.array([sequential_path(local_pairs, initial, output=y)[
                "conditional_path_probability"] for y in range(1 << WIDTH)])
        else:
            local = np.zeros(1 << WIDTH, dtype=float)
            for gi in range(g):
                initial = np.zeros(dim, dtype=complex)
                initial[gi*B] = 1.
                local += np.array([sequential_path(local_pairs, initial, output=y)[
                    "conditional_path_probability"] for y in range(1 << WIDTH)]) / g
        result += (g / M) * local
        details.append(dict(group=list(group), size=g, dimension=dim,
                            history_count=2 ** len(reflection_qs)))
    return result, details


def main() -> None:
    exp = Experiment("route_regrouping", doc=__doc__)
    exp.predict("P1", "reflection orbit gcd formula and Jq unitary identities hold")
    exp.predict("P2", "one-q coherent grouped finite-work law matches full-r")
    exp.predict("P3", "two-q gcd grouping and history-count-4 law match full-r")
    exp.must_fail("C1", "dropping coherence inside a size-two initial group changes output")
    exp.must_fail("C2", "uniform output law is not the target output marginal")

    rows = []
    # Exact gcd formula, including huge M without M-indexed enumeration.
    gcd_cases = [(5, (0,), 0, 1), (5, (1,), 0, 2), (5, (0, 1), 0, 5),
                 (7, (0, 1), 0, 7), (1_000_000_007, (0,), 0, 1),
                 (1_000_000_007, (1,), 0, 2),
                 (1_000_000_007, (0, 1), 0, 1_000_000_007)]
    for M, qs, alpha, expected_size in gcd_cases:
        g, cosets, predicted = gcd_orbit_size(M, qs, alpha)
        enumerated = len(reflection_orbit(M, qs, alpha)) if M <= 12 else None
        ok = predicted == expected_size and (enumerated is None or enumerated == predicted)
        exp.check("P1", ok,
                  f"M={M}, q={qs}, g={g}, cosets={cosets}, size={predicted}, enum={enumerated}")
        rows.append(dict(series="gcd_orbit", M=M, qs=list(qs), gcd=g,
                         cosets=cosets, predicted_size=predicted, enumerated_size=enumerated))

    finite_gcd_cases = 0
    for finite_M in range(1, 13):
        for finite_qs in ((0,), (1,), (0, 1), (0, 2), (1, 3), (0, 2, 4)):
            for alpha in range(finite_M):
                predicted = gcd_orbit_size(finite_M, finite_qs, alpha)[2]
                actual = len(reflection_orbit(finite_M, finite_qs, alpha))
                if predicted != actual:
                    raise AssertionError((finite_M, finite_qs, alpha, predicted, actual))
                finite_gcd_cases += 1
    exp.check("P1", finite_gcd_cases == 468,
              "468 finite gcd/orbit checks include composite M and every initial sector")

    # Jq must be a Hermitian involution for the cosine/sine gate construction.
    max_j_unitary = max_j_hermitian = 0.
    for r in (10, 14):
        for q in (0, 1, 2):
            J = character(r, q) @ reflection(r, q)
            max_j_unitary = max(max_j_unitary,
                                float(np.max(np.abs(J.conj().T @ J - np.eye(r)))))
            max_j_hermitian = max(max_j_hermitian,
                                  float(np.max(np.abs(J.conj().T - J))))
    exp.check("P1", max_j_unitary < 3e-12 and max_j_hermitian < 3e-12,
              f"Jq unitary={max_j_unitary:.2e}, Hermitian={max_j_hermitian:.2e}")

    # One fixed q at each prime-M fixture: every group has size <=2.
    for r in (10, 14):
        M = r // B
        for q in (0, 1):
            full = full_marginal(r, {2: q})
            grouped, details = grouped_marginal(r, {2: q})
            error = float(np.max(np.abs(full - grouped)))
            sizes = [d["size"] for d in details]
            exp.check("P2", error < 3e-10 and max(sizes) <= 2,
                      f"r={r}, M={M}, q={q}: max={error:.2e}, groups={sizes}")
            rows.append(dict(series="one_reflection", r=r, M=M, q=q,
                             max_error=error, groups=details, full=full.tolist(),
                             grouped=grouped.tolist()))

    # Two q values generate translations by q1-q0; with prime M this is one
    # full group, dimension r, and only four coherent histories.
    two_errors = []
    for r in (10, 14):
        full = full_marginal(r, {2: 0, 4: 1})
        grouped, details = grouped_marginal(r, {2: 0, 4: 1})
        error = float(np.max(np.abs(full - grouped)))
        two_errors.append(error)
        exp.check("P3", error < 3e-10 and len(details) == 1
                  and details[0]["history_count"] == 4,
                  f"r={r}, two q: max={error:.2e}, details={details}")
        rows.append(dict(series="two_reflections", r=r, max_error=error,
                         groups=details, full=full.tolist(), grouped=grouped.tolist()))

    # C1: preserve each size-two group but replace the coherent initial p=0
    # superposition by an incoherent mixture over its members.
    full_one = full_marginal(10, {2: 0})
    incoherent_one, _ = grouped_marginal(10, {2: 0}, coherent_initial=False)
    incoherent_error = 0.5 * float(np.sum(np.abs(full_one - incoherent_one)))
    exp.fail_check("C1", incoherent_error > 1e-5,
                   f"r=10 q=0 dropped-group-coherence TV={incoherent_error:.9g}")

    # C2 concerns the OUTPUT law; it does not test a uniform final sector.
    uniform = np.full(1 << WIDTH, 1 / (1 << WIDTH))
    uniform_error = 0.5 * float(np.sum(np.abs(full_one - uniform)))
    exp.fail_check("C2", uniform_error > 1e-5,
                   f"uniform output target TV={uniform_error:.9g}")
    rows.append(dict(series="controls", incoherent_group_tv=incoherent_error,
                     uniform_output_tv=uniform_error, two_reflection_errors=two_errors))

    path = report_path()
    exp.finish(report_path=path, rows=rows, metadata=dict(
        width=WIDTH, block_size=B, angle=float(ANGLE), max_r=MAX_R,
        background="repeated Rx(pi/2) W after controls 1,3,4",
        one_reflection_insertions=[2], two_reflection_insertions=[2, 4],
        gcd_formula="g=gcd(M,q_i-q_0); one/two residue cosets under reflections",
        huge_M_no_array=True, history_count_two_q=4,
        finite_gcd_cases=finite_gcd_cases,
        max_two_reflection_error=max(two_errors),
        dropped_group_coherence_tv=incoherent_error,
        uniform_output_tv=uniform_error,
        reference="full-r sequential_path vs explicit coherent sector-group sequential_path",
        no_generic_propagator=True))
    print(f"report: {path}")


if __name__ == "__main__":
    try:
        main()
    except BaseException as exc:
        failure = report_path("route_regrouping_failure")
        failure.write_text(json.dumps(dict(ok=False, error=repr(exc),
                                           traceback=traceback.format_exc(),
                                           python=__import__("sys").version), indent=2) + "\n")
        raise

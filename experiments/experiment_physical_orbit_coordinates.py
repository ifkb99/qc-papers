"""Bounded exact audit of physical-orbit coordinate promises.

The indexed input supplies N, a, the exact order r=b*M, and the small cell
size b.  The experiment keeps modular encodings x=a^j mod N separate from the
known test labels j.  It audits cell reflection, rational phase inversion,
and subgroup-table recovery; it does not synthesize gates or evaluate a
phase from an unknown x.

PREDICTIONS, WRITTEN BEFORE MEASURING.

  P1  If the b-entry table p -> a^(M*p) is injective, x^M recovers p and
      a^(2p)/x realizes j=b*m+p -> -b*m+p on every tiny orbit label,
      including composite moduli and gcd(b,M)>1 fixtures.
  P2  A known-j phase oracle with circular error strictly below 1/(2s),
      s=M/gcd(q,M), recovers m modulo s by exact rational rounding and
      inversion of q/gcd(q,M).
  P3  When s is small, x^(r/(b*s)) and a b*s-entry subgroup table recover
      j modulo b*s; the measured table sizes are compared with the exact
      static group generated by the tested route labels.
  P4  Inverse doubling recovers the 1/M phase grid from only uniform
      +/-1/16 circular oracle errors on all small-M sign patterns.

  C1  Plain inversion is not cell reflection away from the p=0 cell.
  C2  A deliberately insufficient phase error causes at least one wrong
      recovered residue on a fixture with s>1.
  C3  Uniform epsilon=.24 causes an actual inverse-doubling lift failure.

The phase oracle in P2 is generated from known j solely as an exact reference;
it is not a classical evaluator from x and must not be read as one.  All
allocations and modular-operation budgets are guarded before growth.  These
rows make no runtime-hardness or gate-synthesis claim.
"""
from __future__ import annotations

import itertools
import math
import time
from fractions import Fraction
from datetime import datetime, timezone
from pathlib import Path

from lab import Experiment


MAX_R = 256
MAX_B = 64
MAX_TABLE_ENTRIES = 256
MAX_OPS = 250_000
MAX_UNWRAP_OPS = 150_000
MAX_UNWRAP_SEQUENCE = 8

exp = Experiment(__name__.rsplit(".", 1)[-1], doc=__doc__, exit_on_fail=False)
exp.predict("P1", "injective x^M fine-coordinate tables realize cell reflection on every tested j")
exp.predict("P2", "strict rational phase accuracy recovers m modulo the exact phase order")
exp.predict("P3", "subgroup tables recover j modulo b*s and agree with static route grouping")
exp.predict("P4", "inverse-doubling recovers all small-M residues under every +/-1/16 oracle pattern")
exp.must_fail("C1", "plain inversion fails as a replacement for cell reflection")
exp.must_fail("C2", "insufficient phase precision causes a wrong residue")
exp.must_fail("C3", "epsilon=.24 produces an actual inverse-doubling lift failure")


class Budget:
    def __init__(self, limit=MAX_OPS):
        self.limit = int(limit)
        self.operations = 0

    def add(self, amount=1):
        self.operations += int(amount)
        if self.operations > self.limit:
            raise MemoryError(f"physical-coordinate operation budget exceeded: "
                              f"{self.operations}>{self.limit}")

    def preflight(self, amount, label):
        amount = int(amount)
        if amount < 0 or self.operations + amount > self.limit:
            raise MemoryError(f"{label} preflight exceeds operation budget: "
                              f"{self.operations + amount}>{self.limit}")


def guard(entries, label):
    if type(entries) is not int or entries < 0 or entries > MAX_TABLE_ENTRIES:
        raise MemoryError(f"{label} exceeds {MAX_TABLE_ENTRIES} entries")


def report_path():
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    path = Path("out") / f"physical_orbit_coordinates_{stamp}.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    return path


def proper_order(a, modulus, claimed, budget):
    """Check the supplied order using only the frozen tiny bound."""
    if not (1 <= claimed <= MAX_R):
        raise ValueError("fixture order outside frozen bound")
    budget.add(claimed)
    if pow(a, claimed, modulus) != 1:
        return False
    for d in range(1, claimed):
        if claimed % d == 0:
            budget.add(1)
            if pow(a, d, modulus) == 1:
                return False
    return True


def fixture_guard(N, a, b, M, r, budget):
    if not all(isinstance(v, int) for v in (N, a, b, M, r)):
        raise ValueError("fixture integers required")
    if N < 2 or not 1 <= b <= MAX_B or not 1 <= M or r != b*M:
        raise ValueError("invalid supplied r=b*M fixture")
    if r > MAX_R or math.gcd(a, N) != 1:
        raise ValueError("fixture exceeds order or unit bounds")
    if not proper_order(a % N, N, r, budget):
        raise ValueError("supplied order is not exact")


def orbit_encodings(N, a, r, budget):
    guard(r, "orbit encoding")
    budget.add(r)
    return [pow(a, j, N) for j in range(r)]


def cell_reflection(N, a, b, M, r, budget):
    guard(r + b, "orbit encoding plus fine-coordinate table")
    xs = orbit_encodings(N, a, r, budget)
    guard(b, "fine-coordinate table")
    table = {}
    budget.add(1)
    a_to_M = pow(a, M, N)
    for p in range(b):
        budget.add(1)
        value = pow(a_to_M, p, N)
        if value in table:
            table[value] = None
        else:
            table[value] = p
    injective = all(value is not None for value in table.values())
    reflection_mismatches = plain_mismatches = p_failures = 0
    for j, x in enumerate(xs):
        m, p = divmod(j, b)
        budget.add(4)
        x_power = pow(x, M, N)
        recovered = table.get(x_power)
        if recovered != p:
            p_failures += 1
        expected_j = (-b*m + p) % r
        expected_x = xs[expected_j]
        if recovered is None:
            reflection_mismatches += 1
        else:
            reflected_x = (pow(a, 2*recovered, N) * pow(x, -1, N)) % N
            reflection_mismatches += reflected_x != expected_x
        plain_mismatches += pow(x, -1, N) != expected_x
    return {
        "table_entries": len(table), "table_injective": injective,
        "p_recovery_failures": p_failures,
        "reflection_mismatches": reflection_mismatches,
        "plain_inversion_mismatches": plain_mismatches,
    }


def mod1(value):
    value %= 1
    return value


def circular_distance(x, y):
    delta = mod1(x-y)
    return min(delta, 1-delta)


def phase_from_known_j(j, b, q, M):
    """Reference oracle only: generate D_q's phase from known j."""
    m = j // b
    return Fraction((q*m) % M, M)


def recover_m_mod_s(observed, q, M):
    d = math.gcd(q, M)
    s = M // d
    if s == 1:
        return 0
    scaled = observed * s
    nearest = (scaled + Fraction(1, 2)).numerator // (scaled + Fraction(1, 2)).denominator
    residue = nearest % s
    inverse = pow((q // d) % s, -1, s)
    return (inverse * residue) % s


def phase_audit(N, a, b, M, r, budget):
    xs = orbit_encodings(N, a, r, budget)
    del xs  # phase reference is deliberately generated from j, not evaluated from x
    good_failures = bad_wrong = 0
    bad_witness = None
    rows = []
    for q in range(1, M):
        d = math.gcd(q, M)
        s = M // d
        good_error = Fraction(3, 8*s)
        good_failures_q = 0
        for j in range(r):
            true = phase_from_known_j(j, b, q, M)
            for sign in (-1, 1):
                observed = mod1(true + sign*good_error)
                budget.add(2)
                good_failures_q += (circular_distance(observed, true) >= Fraction(1, 2*s)
                                     or recover_m_mod_s(observed, q, M) != (j//b) % s)
        good_failures += good_failures_q
        rows.append({"q": q, "s": s, "good_failures": good_failures_q,
                     "oracle_source": "known_j_exact_reference"})
    # A one-grid-step error is deliberately outside the strict promise.  The
    # M=4,q=1 row has s=4, so this is a genuine nontrivial wrong-residue test.
    q_bad = 1 if M > 1 else 0
    s_bad = M // math.gcd(q_bad, M) if q_bad else 1
    for j in range(r):
        true = phase_from_known_j(j, b, q_bad, M)
        observed = mod1(true + Fraction(1, s_bad)) if s_bad > 1 else true
        budget.add(1)
        recovered = recover_m_mod_s(observed, q_bad, M)
        wrong = s_bad > 1 and recovered != (j//b) % s_bad
        bad_wrong += wrong
        if wrong and bad_witness is None:
            bad_witness = {"q": q_bad, "j": j, "s": s_bad,
                           "true": true, "observed": observed,
                           "error": circular_distance(observed, true),
                           "expected": (j//b) % s_bad,
                           "recovered": recovered}
    return {"rows": rows, "good_failures": good_failures,
            "insufficient_precision_wrong": bad_wrong,
            "insufficient_precision_witness": bad_witness}


def phase_bit_length(M):
    length = 0
    while (1 << length) < M:
        length += 1
    return length


def inverse_double_decode(noisy_sequence, budget):
    """Decode solely from noisy phase turns, descending by inverse doubling."""
    if not 1 <= len(noisy_sequence) <= MAX_UNWRAP_SEQUENCE:
        raise ValueError("noisy sequence outside frozen inverse-doubling bound")
    estimate = noisy_sequence[-1]
    for index in range(len(noisy_sequence)-2, -1, -1):
        candidates = (mod1(estimate / 2), mod1((estimate + 1) / 2))
        distances = tuple(circular_distance(candidate, noisy_sequence[index])
                          for candidate in candidates)
        budget.add(3)
        estimate = candidates[0] if distances[0] <= distances[1] else candidates[1]
    return estimate


def rounded_grid_residue(phase, modulus):
    scaled = phase * modulus
    nearest = (scaled + Fraction(1, 2)).numerator // (scaled + Fraction(1, 2)).denominator
    return nearest % modulus


def sign_patterns(length, *, selected=False):
    guard(length, "inverse-doubling sequence")
    count = 1 << length
    if not selected:
        return tuple(itertools.product((-1, 1), repeat=length))
    # Four fixed adversarial patterns for wider selected moduli.
    return ((1,)*length, (-1,)*length,
            tuple(1 if bit % 2 == 0 else -1 for bit in range(length)),
            tuple(-1 if bit % 2 == 0 else 1 for bit in range(length)))


def unwrap_audit(budget):
    epsilon = Fraction(1, 16)
    positive_failures = 0
    positive_cases = 0
    rows = []
    moduli = tuple(range(2, 17)) + (17, 31, 64, 127)
    positive_plan = 0
    for M in moduli:
        length = phase_bit_length(M) + 1
        pattern_count = len(sign_patterns(length, selected=M > 16))
        positive_plan += M * pattern_count * (4*length - 3)
    negative_plan = sum(M * len(sign_patterns(phase_bit_length(M)+1))
                        * (4*(phase_bit_length(M)+1)-3)
                        for M in range(2, 17))
    budget.preflight(positive_plan + negative_plan,
                     "inverse-doubling exact-operation")
    for M in moduli:
        length = phase_bit_length(M) + 1
        patterns = sign_patterns(length, selected=M > 16)
        failures_M = 0
        for m in range(M):
            for signs in patterns:
                # The decoder receives only this noisy oracle sequence; m is
                # retained solely as the exact reference for verification.
                observed = tuple(mod1(Fraction(m * (1 << i), M)
                                    + signs[i] * epsilon)
                                for i in range(length))
                decoded = inverse_double_decode(observed, budget)
                recovered = rounded_grid_residue(decoded, M)
                budget.add(length)
                failures_M += (recovered != m or
                    circular_distance(decoded, Fraction(m, M)) > epsilon/(1 << (length-1)))
        positive_failures += failures_M
        positive_cases += M * len(patterns)
        rows.append({"M": M, "sequence_length": length,
                     "pattern_count": len(patterns),
                     "failures": failures_M,
                     "oracle_source": "known_m_exact_reference"})

    # Concrete negative witness search.  epsilon=.24 is below 1/4 but violates
    # the sufficient local condition epsilon+epsilon/2<1/4.
    bad_epsilon = Fraction(6, 25)
    witness = None
    for M in range(2, 17):
        length = phase_bit_length(M) + 1
        for m in range(M):
            for signs in sign_patterns(length):
                observed = tuple(mod1(Fraction(m * (1 << i), M)
                                    + signs[i] * bad_epsilon)
                                for i in range(length))
                decoded = inverse_double_decode(observed, budget)
                recovered = rounded_grid_residue(decoded, M)
                budget.add(length)
                if recovered != m and witness is None:
                    witness = {"M": M, "m": m, "signs": signs,
                               "decoded": decoded, "recovered": recovered,
                               "epsilon": bad_epsilon, "observed": observed,
                               "true_phase": Fraction(m, M)}
                    break
            if witness is not None:
                break
        if witness is not None:
            break
    return {"epsilon": epsilon, "positive_cases": positive_cases,
            "positive_failures": positive_failures, "rows": rows,
            "negative_witness": witness}


def subgroup_table_audit(N, a, b, M, r, q_values, budget):
    subgroup_sizes = tuple(b * (M // math.gcd(q, M)) for q in q_values)
    if any(r % L for L in subgroup_sizes):
        raise AssertionError("b*s must divide r")
    guard(r + max(subgroup_sizes, default=0),
          "orbit encoding plus largest subgroup table")
    xs = orbit_encodings(N, a, r, budget)
    rows = []
    for q, L in zip(q_values, subgroup_sizes):
        s = M // math.gcd(q, M)
        guard(L, "subgroup table")
        h = pow(a, r//L, N)
        table = {}
        for residue in range(L):
            budget.add(1)
            value = pow(h, residue, N)
            if value in table:
                raise AssertionError("exact-order subgroup table collided")
            table[value] = residue
        failures = 0
        for j, x in enumerate(xs):
            budget.add(2)
            recovered = table.get(pow(x, r//L, N))
            failures += recovered != j % L
        rows.append({"q": q, "s": s, "table_entries": L,
                     "recovery_failures": failures})
    return rows


def static_group_audit(M, q_values, budget):
    q_values = tuple(q % M for q in q_values)
    q0 = q_values[0]
    g = math.gcd(M, *(q-q0 for q in q_values[1:]))
    translation_size = M // g
    rows = []
    for alpha in range(M):
        predicted = (translation_size if (2*alpha+q0) % g == 0
                     else 2*translation_size)
        generated = {alpha}
        retained = 1
        guard(retained, "generated static-group closure")
        while True:
            old = tuple(generated)
            guard(retained + len(old)*len(q_values),
                  "generated static-group closure before growth")
            for value in old:
                for q in q_values:
                    budget.add(1)
                    generated.add((-value-q) % M)
            guard(len(generated), "generated static-group closure")
            if len(generated) == len(old):
                break
            retained += len(generated)
            guard(retained, "generated static-group retained references")
        rows.append((len(generated), predicted))
    phase_lcm = math.lcm(*[M//math.gcd(q, M) for q in q_values])
    return {"gcd_difference": g, "translation_size": translation_size,
            "max_formula_mismatch": max(abs(a-p) for a,p in rows),
            "lcm_phase_orders": phase_lcm,
            "translation_le_lcm": translation_size <= phase_lcm,
            "max_group_le_2lcm": max((a for a,p in rows), default=0) <= 2*phase_lcm}


def fixture_audit(name, fixture, q_values, budget):
    N, a, b, M, r = fixture
    fixture_guard(N, a, b, M, r, budget)
    cell = cell_reflection(N, a, b, M, r, budget)
    phase = phase_audit(N, a, b, M, r, budget)
    subgroup = subgroup_table_audit(N, a, b, M, r, q_values, budget)
    static = static_group_audit(M, q_values, budget)
    return {"name": name, "N": N, "a": a, "b": b, "M": M, "r": r,
            "gcd_b_M": math.gcd(b, M), "cell": cell, "phase": phase,
            "subgroup": subgroup, "static_group": static}


def json_safe(value):
    if isinstance(value, Fraction):
        return {"numerator": value.numerator,
                "denominator": value.denominator}
    if isinstance(value, dict):
        return {str(k): json_safe(v) for k, v in value.items()}
    if isinstance(value, (list, tuple, set, frozenset)):
        return [json_safe(v) for v in value]
    return value


def main():
    started = time.perf_counter()
    report = {"status": "PASS", "fixtures": [], "operations": 0,
              "unwrap": {}, "unwrap_operations": 0}
    p1 = p2 = p3 = p4 = c1 = c2 = c3 = False
    try:
        budget = Budget()
        fixtures = (
            ("prime_b3_M2", (7, 3, 3, 2, 6), (1,)),
            ("prime_b3_M4", (13, 2, 3, 4, 12), (1, 2, 3)),
            ("prime_gcd_bM", (13, 2, 6, 2, 12), (1,)),
            ("composite_gcd_bM", (35, 2, 6, 2, 12), (1,)),
            ("composite_b2_M2", (15, 2, 2, 2, 4), (1,)),
            ("prime_subgroup_small_s", (17, 3, 4, 4, 16), (1, 2)),
            ("prime_large_M_small_phase_orders", (97, 5, 3, 32, 96), (0, 8, 16)),
        )
        for name, fixture, q_values in fixtures:
            report["fixtures"].append(fixture_audit(
                name, fixture, q_values, budget))
        p1 = all(row["cell"]["table_injective"]
                  and row["cell"]["p_recovery_failures"] == 0
                  and row["cell"]["reflection_mismatches"] == 0
                  for row in report["fixtures"])
        p2 = all(row["phase"]["good_failures"] == 0
                 for row in report["fixtures"])
        p3 = all(all(item["recovery_failures"] == 0
                     for item in row["subgroup"])
                 and row["static_group"]["max_formula_mismatch"] == 0
                 and row["static_group"]["translation_le_lcm"]
                 and row["static_group"]["max_group_le_2lcm"]
                 for row in report["fixtures"])
        c1 = any(row["cell"]["plain_inversion_mismatches"] > 0
                 for row in report["fixtures"])
        c2 = any(row["phase"]["insufficient_precision_wrong"] > 0
                 for row in report["fixtures"])
        report["operations"] = budget.operations
        unwrap_budget = Budget(MAX_UNWRAP_OPS)
        report["unwrap"] = unwrap_audit(unwrap_budget)
        report["unwrap_operations"] = unwrap_budget.operations
        p4 = report["unwrap"]["positive_failures"] == 0
        c3 = report["unwrap"]["negative_witness"] is not None
        report["status"] = ("PASS" if p1 and p2 and p3 and p4
                             and c1 and c2 and c3 else "FAIL")
        exp.check("P1", p1, "cell reflection matches all supplied prime/composite orbit labels")
        exp.check("P2", p2, "strict exact phase errors recover all tested residues")
        exp.check("P3", p3, "subgroup tables and static group formulas agree")
        exp.check("P4", p4, "constant-error inverse doubling recovers all audited residues")
        exp.fail_check("C1", c1, "plain inversion is refuted as cell reflection")
        exp.fail_check("C2", c2, "insufficient phase precision is refuted")
        exp.fail_check("C3", c3, "epsilon=.24 has an explicit wrong-lift witness")
    except Exception as exc:
        report["status"] = "FAIL"
        report["exception"] = repr(exc)
        report["traceback"] = __import__("traceback").format_exc()
        exp.log("EXCEPTION", repr(exc))
        for name in ("P1", "P2", "P3", "P4"):
            exp.check(name, False, "exception before completion")
        for name in ("C1", "C2", "C3"):
            exp.fail_check(name, False, "exception before control")
    report["elapsed_seconds"] = time.perf_counter() - started
    path = report_path()
    ok = exp.finish(report_path=path, rows=[json_safe(report)], metadata={
        "max_order": MAX_R, "max_block_size": MAX_B,
        "max_table_entries": MAX_TABLE_ENTRIES,
        "max_operations": MAX_OPS,
        "max_unwrap_operations": MAX_UNWRAP_OPS,
        "max_total_operations": MAX_OPS + MAX_UNWRAP_OPS,
        "max_unwrap_sequence": MAX_UNWRAP_SEQUENCE,
        "operation_scope": "exact charged modular calls, reference set updates and Fraction decoder steps; not native instructions or RSS",
        "phase_oracle_source": "known j exact reference; no x-to-phase evaluator",
        "allocations_guarded_before_growth": True,
        "no_generic_propagator": True,
    })
    print(f"report: {path}")
    if not ok:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
